/** обрывок главы для вступления: абзац средней длины (детерминированно) */
function excerptOf(i) {
  const F = GAMES[i];
  if (F.text) return F.text;
  const ps = (BOOK[i] ? BOOK[i].p : []).filter(p => p !== '---' && p.length > 90 && p.length < 420 && !/^[·•\d]/.test(p));
  if (!ps.length) return (BOOK[i] && BOOK[i].p[0]) || '';
  return ps[hash(F.id) % Math.min(ps.length, 6)];
}

