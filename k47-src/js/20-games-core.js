  /** главный вход: вернёт статус главы после всех попыток (или null, если отказались до игры) */
  async function play(i) {
    if (busy) return null;
    busy = true;
    try {
      const choice = await intro(i);
      if (!choice) return null;
      if (choice === 'skip') { const c = chState(i); if (!c.st) c.st = 'dmg'; Save.put(); return c.st; }
      for (;;) {
        const r = await run(i);
        if (r.ok === 'abort') return chStatus(i);
        const wear = apply(i, r);
        const next = await result(i, r, wear);
        if (G.wear >= 100 || next !== 'again') return chStatus(i);
      }
    } finally {
      busy = false;
      A.setAmbient(actName === 'room' ? 'reader' : null, 1);
    }
  }
