const NORM_HOLD = 2600;   // его фраза держится не меньше этого, даже если жать быстро

function setupNorm(ctx) {
  const { scope } = ctx;
  const C = GameState.clicks, S = GameState.story;
  const status = $('#normStatus'), victim = $('#normVictim'), villain = $('#normVillain');
  const fill = $('#normFill'), progress = $('#normProgress'), count = $('#normCount'), btn = $('#normBtn'), word = $('#normWord'), cool = $('#normCool');
  let done = false, shownAt = -1e9, pending = null, pendingT = 0;

  function render() {
    fill.style.width = `${(C.count / CLICKS_NEEDED) * 100}%`;
    count.textContent = C.count;
    btn.setAttribute('aria-label', `Нажать. Осталось ${CLICKS_NEEDED - C.count}`);
    const ok = C.count >= CLICKS_NEEDED;
    progress.classList.toggle('done', ok); status.classList.toggle('done', ok);
    status.textContent = ok ? 'НОРМА РАСХОДА ПЛОТИ ДОСТИГНУТА.' : 'НОРМА РАСХОДА ПЛОТИ НЕ ДОСТИГНУТА';
  }
  async function say(text) {
    villain.classList.remove('show');
    await scope.wait(400);
    villain.textContent = text; villain.className = 'norm-villain show';
  }
  /** его реплика: сразу, если прошлая уже прозвучала; иначе — когда прозвучит (берётся самая свежая) */
  function voice(text) {
    const wait = shownAt + NORM_HOLD - Clock.now();
    if (wait <= 0) { showVoice(text); return; }
    pending = text;
    if (!pendingT) pendingT = scope.timeout(() => { pendingT = 0; if (pending) { showVoice(pending); pending = null; } }, wait);
  }
  function showVoice(text) {
    shownAt = Clock.now();
    villain.classList.remove('show'); void villain.offsetWidth;
    villain.textContent = text; villain.className = 'norm-villain show';
    cool.style.transition = 'none'; cool.style.transform = 'scaleX(1)'; void cool.offsetWidth;
    cool.style.transition = `transform ${NORM_HOLD}ms linear`; cool.style.transform = 'scaleX(0)';
  }
  function start() {
    Audio47.setAmbient('clicks');
    Audio47.setIntensity(C.count / CLICKS_NEEDED);
    done = false; pending = null;
    victim.className = 'norm-victim'; victim.textContent = ''; word.textContent = '';
    btn.hidden = false; btn.disabled = false;
    cool.style.transition = 'none'; cool.style.transform = 'scaleX(0)';
    showVoice(C.count ? PAIRS[C.count - 1][1] : 'Сорок семь нажатий. Каждое — смерть. Нажимай.');
    render();
    ctx.log(`Норма расхода плоти: ${C.count} / ${CLICKS_NEEDED}`, 'warn');
    if (C.count >= CLICKS_NEEDED) complete();
  }
  /** без пауз: каждое нажатие — сразу крик и смерть; его голос — с задержкой, не чаще NORM_HOLD */
  function press() {
    if (done || C.count >= CLICKS_NEEDED || ctx.phase !== 'terminal') return;
    C.count++; Save.clicks();
    const [v, w] = PAIRS[C.count - 1];
    word.textContent = pick(DEATH_WORDS);
    victim.textContent = v; victim.className = 'norm-victim'; void victim.offsetWidth; victim.className = 'norm-victim show';
    render();
    FX.redBlack();
    Audio47.sfx.heartbeat(0.4 + (C.count / CLICKS_NEEDED) * 0.6);
    Audio47.setIntensity(C.count / CLICKS_NEEDED);
    if (Math.random() < 0.4) FX.addBlood(1);
    FX.vibrate(25);
    if (C.count >= CLICKS_NEEDED) { scope.clear(pendingT); pendingT = 0; pending = null; showVoice(w); complete(); return; }
    voice(w);
  }
  async function complete() {
    done = true; C.done = true; btn.disabled = true;
    GameState.agingLevel = Math.max(GameState.agingLevel, 0.5);
    FX.setLevel(GameState.agingLevel); FX.bump(0.9); FX.addBlood(3); FX.shake('lg'); FX.vibrate([100, 50, 200]);
    Audio47.sfx.glitch(2.4);
    render();
    word.textContent = '';
    await scope.wait(1300);
    btn.hidden = true; victim.className = 'norm-victim';
    await say('Кажется, ты выполнил норму расхода плоти.'); await scope.wait(3200);
    await say('Свою задачу ты выполнил.'); await scope.wait(3000);
    await say('А теперь — обернись.'); await scope.wait(2800);
    S.stage = 'feel'; Save.progress(); Save.clicks();
    ctx.exitTerminal({ auto: true });
  }
  scope.on(btn, 'click', press);
  ctx.norm = { start };
}
