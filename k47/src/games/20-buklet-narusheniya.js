defineFrag(19, {
  id: 'booklet', name: 'Нарушения',
  text: '«Класс Актив: нормы расхода плоти, цикличность, утилизация». Логотип корпорации на обложке выцвел от частых прикосновений. — Как не начать видеть, — поправил техник. — Тонкая разница.',
  how: 'Журнал камер за смену. Для каждого события реши: норма это или нарушение правил буклета — и какого именно. Правила: зрительный контакт дольше трёх секунд, лишние вопросы, прикосновения, запоминание номеров, эмоции, информирование клона, пропуск признаков самосознания. Нужно 8 верных из 10.',
  keys: 'ОТВЕТ — КНОПКИ ИЛИ 1 / 2 / 3 · НА КАЖДОЕ СОБЫТИЕ — 12 СЕКУНД',
  note: '«Клоны не читают буклетов», — думал техник. Брошюры остались в тумбочке. Три. О том, как не видеть. Все знали, где они.',
  noteDist: 'В этой записи техник подал рапорт — на повара, на смотрителя, на себя. Архив говорит, что брошюры просто остались в тумбочке.',
  mem: 'ПРАВИЛО ЧЕТВЁРТОЕ', start: gameBooklet,
});

function gameBooklet(ctx) {
  const { scope } = ctx;
  const RULES = {
    1: 'Зрительный контакт дольше 3 с', 2: 'Лишние вопросы клону', 3: 'Прикосновение без нужды', 4: 'Запоминание номеров',
    5: 'Эмоциональная реакция', 6: 'Информирование клона', 7: 'Пропущен признак самосознания',
  };
  const EVENTS = shuffle([
    ['Смотритель сам затянул лямки бронежилета на клоне. Поправил плечи.', 3],
    ['Техник выписывает номер К-26 на полях буклета.', 4],
    ['Лаборантка у капсулы смотрит клону в глаза. Шесть секунд. Семь.', 1],
    ['Повар спросил клона на раздаче: «Вкусно?»', 2],
    ['Клон в камере спросил в пустоту: «За что?» Оператор продолжил смену.', 7],
    ['Брошюра «Класс Актив» оставлена открытой в комнате ожидания клона.', 6],
    ['Наблюдательница плачет над монитором после гибели К-38.', 5],
    ['Санитар маркирует тело биркой. Мешок. Носилки. Машина.', 0],
    ['Смотритель у капсулы: «Иди. Стой. Жди».', 0],
    ['Техник проверяет давление и уровень геля в капсуле К-29.', 0],
    ['Оператор вносит гибель К-19 в сменный отчёт.', 0],
  ]).slice(0, 10);
  const hum = scope.own(A.loopOsc({ type: 'sine', freq: 60, vol: 0 }));
  hum.vol(0.02, 1);
  const cams = [];
  const items = EVENTS.map(([q, rule], n) => {
    const others = shuffle(Object.keys(RULES).map(Number).filter(r => r !== rule)).slice(0, 2);
    const opts = shuffle(rule ? [rule, 0, others[0]] : [0, others[0], others[1]]);
    const labels = opts.map(r => (r === 0 ? 'Норма. Нарушений нет' : `Нарушение п.${r}: ${RULES[r].toLowerCase()}`));
    cams.push(irand(1, 12));
    return { q: `КАМЕРА ${String(cams[n]).padStart(2, '0')} · ${q}`, opts: labels, a: opts.indexOf(rule), why: rule ? `Буклет, п.${rule}: ${RULES[rule]}.` : 'Процедура. Никто не смотрел дольше положенного.', pic: camPic(n) };
  });
  function camPic(n) {
    return (g, W, H, t) => {
      g.fillStyle = '#050807'; g.fillRect(0, 0, W, H);
      const R = mulberry(n * 17 + 3);
      g.fillStyle = '#0d1512'; g.fillRect(W * 0.05, H * 0.1, W * 0.9, H * 0.8);
      for (let i = 0; i < 2; i++) Art.human(g, W * (0.35 + i * 0.3 + (R() - 0.5) * 0.1), H * 0.88, H * (0.6 + R() * 0.15), i ? 'man' : pick(['doctor', 'man']), { color: 'rgba(160,210,190,.35)', eyes: i ? '#ffffff' : null });
      g.fillStyle = 'rgba(0,255,136,.07)'; for (let y = 0; y < H; y += 3) g.fillRect(0, y, W, 1);
      g.fillStyle = 'rgba(0,255,136,.8)'; g.font = `10px ${MONO}`; g.textAlign = 'left';
      g.fillText(`CAM ${String(cams[n]).padStart(2, '0')} · КУПОЛ-7 · ${new Date(Date.UTC(2999, 3, 15, 23, (n * 7) % 60, Math.floor(t) % 60)).toISOString().slice(11, 19)}`, 8, 14);
      if (Math.floor(t * 2) % 2) { g.fillStyle = '#ff0033'; g.beginPath(); g.arc(W - 14, 10, 4, 0, Math.PI * 2); g.fill(); }
      if (Math.random() < 0.05) { g.fillStyle = 'rgba(0,255,136,.15)'; g.fillRect(0, Math.random() * H, W, 8); }
    };
  }
  ctx.hint('НОРМА ИЛИ НАРУШЕНИЕ — И КАКОЕ ИМЕННО');

  return (async () => {
    await ctx.line('Конец смены. Мониторы показывают ровные зелёные линии.', { pos: 'top', ms: 2200 });
    const r = await mgQuiz(ctx, items, { time: 12, title: 'СМЕННЫЙ ЖУРНАЛ', cls: 'ice' });
    ctx.stat(`ВЕРНО ${r.right}/10`);
    if (r.right < 8) {
      await ctx.line('Сменщик пролистал журнал и хмыкнул: «Ты вообще читал буклет?»', { pos: 'mid', cls: 'red', ms: 2800 });
      return { ok: 'fail', detail: `ВЕРНО ${r.right}/10 · НУЖНО 8` };
    }
    await ctx.line('Нарушения найдены. Все — одного рода: кто-то видел в клоне человека.', { pos: 'top', ms: 3000 });
    const k = await ctx.choose(['Убрать брошюры в тумбочку', 'Подать рапорт']);
    if (k === 0) {
      A.sfx.thud(0.2);
      await ctx.line('Он сунул две брошюры в тумбочку. Одну оставил на столе.', { pos: 'top', ms: 2600 });
      return { ok: 'ok', detail: `ВЕРНО ${r.right}/10` };
    }
    A.sfx.stamp(); A.sfx.glitch();
    await ctx.line('Рапорт ушёл наверх. Семь фамилий.', { pos: 'top', ms: 2200 });
    ctx.say('НЕЙРОСЛЕПОК: РАСХОЖДЕНИЕ С ЗАПИСЬЮ', { pos: 'mid', cls: 'big red' });
    await scope.wait(2200);
    return { ok: 'dist', detail: `ВЕРНО ${r.right}/10 · РАПОРТ` };
  })();
}
