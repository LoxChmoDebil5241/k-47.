/** силуэт ствола на голограмме */
function drawGun(g, W, H, kind, t = 0, color = '255,0,51') {
  const s = Math.min(W / 300, H / 150), cx = W / 2, cy = H * 0.55;
  g.save(); g.translate(cx, cy); g.scale(s, s);
  g.fillStyle = `rgba(${color},.22)`; g.strokeStyle = `rgba(${color},.95)`; g.lineWidth = 1.6 / s * s;
  const shape = (pts) => { g.beginPath(); pts.forEach(([x, y], i) => (i ? g.lineTo(x, y) : g.moveTo(x, y))); g.closePath(); g.fill(); g.stroke(); };
  const L = { bur: 90, buran: 110, pump: 130, sawn: 70, wt: 70, vector: 90, mg: 150, sniper: 160, pistol: 38, magnum: 52, laser: 120 }[kind] || 100;
  // ствол
  shape([[-40, -8], [L - 40, -8], [L - 40, 0], [-40, 0]]);
  // корпус
  shape([[-70, -14], [-10, -14], [-10, 8], [-40, 8], [-46, 26], [-58, 26], [-60, 8], [-70, 8]]);
  if (kind === 'buran') { g.beginPath(); g.arc(0, 20, 20, 0, Math.PI * 2); g.fill(); g.stroke(); }
  if (kind === 'bur' || kind === 'wt' || kind === 'vector') shape([[-20, 8], [-10, 8], [-8, 34], [-18, 34]]);
  if (kind === 'pump') shape([[10, 0], [50, 0], [50, 8], [10, 8]]);
  if (kind === 'mg') { shape([[-20, 8], [10, 8], [10, 26], [-20, 26]]); g.beginPath(); g.moveTo(80, 0); g.lineTo(70, 30); g.moveTo(80, 0); g.lineTo(92, 30); g.stroke(); }
  if (kind === 'sniper') { shape([[-50, -26], [10, -26], [10, -18], [-50, -18]]); g.beginPath(); g.moveTo(90, 0); g.lineTo(84, 26); g.moveTo(90, 0); g.lineTo(98, 26); g.stroke(); }
  if (kind !== 'sawn' && kind !== 'wt' && kind !== 'pistol' && kind !== 'magnum') shape([[-70, -12], [-120, -4], [-120, 14], [-70, 6]]);
  if (kind === 'vector') shape([[L - 40, -12], [L - 22, -12], [L - 22, 4], [L - 40, 4]]);
  if (kind === 'laser') { g.fillStyle = `rgba(${color},${0.3 + 0.3 * Math.sin(t * 8)})`; g.fillRect(-40, -22, 40, 8); for (let i = 0; i < 4; i++) g.fillRect(-60 + i * 10, 10, 6, 10); }
  g.restore();
}

